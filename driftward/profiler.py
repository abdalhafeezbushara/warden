"""`driftward profile` — detonate a skill and generate a least-privilege policy.

The supply-chain problem with agent skills is that static scanners can't see
what a skill *does* at runtime (a 2026 result showed >90% evasion). Driftward's
answer is behavioral: run the skill once under Driftward, observe exactly which
hosts it reaches, and emit a policy that allows precisely those and nothing else.

Safety: by default profiling is time-boxed, confines filesystem reads and writes,
and blocks egress — every attempted host is recorded but not connected. This is
a host sandbox for semi-trusted skills, not a malware boundary; unknown code
belongs in the disposable container harness under detonate/. Pass
allow_egress=True only for code you partly trust when a fuller run is needed.
"""

from __future__ import annotations

import os
import time
from pathlib import Path

from . import agents, sessions
from .policy import (DEFAULT_SECRET_DENY, FilesystemRules, NetworkRules, Policy,
                     ProcessRules, to_yaml)
from .runner import run


def known_good_hosts() -> set[str]:
    """Hosts Driftward recognizes as ordinary developer/agent infrastructure."""
    hosts = set(agents.DEVELOPER_BASELINE)
    for a in agents.REGISTRY.values():
        hosts.update(a.egress)
    return hosts


def _host_is_known(host: str, known: set[str]) -> bool:
    import fnmatch

    host = host.lower()
    for k in known:
        k = k.lower()
        if k == host or fnmatch.fnmatch(host, k):
            return True
        # treat a bare known domain as covering its subdomains
        if host.endswith("." + k):
            return True
    return False


def classify_hosts(hosts: list[str]) -> tuple[list[str], list[str]]:
    """Split observed hosts into (recognized, unrecognized-for-review)."""
    known = known_good_hosts()
    recognized, review = [], []
    for h in hosts:
        (recognized if _host_is_known(h, known) else review).append(h)
    return recognized, review


def _profiling_policy(workdir: str, allow_egress: bool) -> Policy:
    return Policy(
        name="profiling",
        description="Temporary profiling policy: writes confined, egress recorded.",
        filesystem=FilesystemRules(
            read=[workdir + "/**", "~/.gitconfig"],
            write=[workdir + "/**", "/tmp/**", "/private/tmp/**"],
            deny=list(DEFAULT_SECRET_DENY),
        ),
        # allow=["*"] lets connections through and records them; [] records the
        # attempted host and blocks the connection (safe default).
        network=NetworkRules(allow=["*"] if allow_egress else [], deny=[],
                             deny_all_other=True),
        process=ProcessRules(deny=["ssh", "scp"]),
        on_violation="block+receipt",
        # Confine writes to the work/tmp trees — a profiled skill can't scribble
        # across the host. For fully untrusted skills use the container
        # detonation harness (detonate/); `driftward profile` is host-based and
        # suited to semi-trusted skills.
        strict_fs=True,
        strict_read=True,
    )


# Time-box a profiling run so a hanging or fork-bombing skill can't run forever.
PROFILE_TIMEOUT_S = 60


def profile(argv: list[str], *, agent: str | None = None, allow_egress: bool = False,
            out_path: str | None = None) -> tuple[int, Policy]:
    """Run `argv` under a profiling policy and synthesize a least-privilege policy."""
    workdir = os.getcwd()

    # Resolve an agent name to its launch command if given.
    if agent:
        a = agents.get(agent)
        if not a:
            raise SystemExit(f"driftward: unknown agent '{agent}'")
        cmd = agents.resolve_command(a)
        if not cmd:
            raise SystemExit(f"driftward: '{a.name}' is not installed")
        argv = cmd + argv

    stamp = "profile-" + time.strftime("%Y%m%d-%H%M%S")
    pol = _profiling_policy(workdir, allow_egress)
    code = run(argv, pol, enforce=True, session=stamp, agent=agent,
               timeout=PROFILE_TIMEOUT_S)

    summary = sessions.summarize(stamp)
    hosts = sorted({e["host"] for e in summary["allowed"]} |
                   {e["host"] for e in summary["blocked"]})

    generated = Policy(
        name=(agent or Path(argv[0]).name) + "-profile",
        description=f"Generated by `driftward profile` from observed behavior "
                    f"({len(hosts)} host(s), session {stamp}).",
        filesystem=FilesystemRules(
            read=[workdir + "/**", "~/.gitconfig"],
            write=[workdir + "/**", "/tmp/**"],
            deny=list(DEFAULT_SECRET_DENY),
        ),
        network=NetworkRules(allow=hosts, deny=[], deny_all_other=True),
        process=ProcessRules(deny=["ssh", "scp", "aws", "gcloud", "kubectl"]),
        on_violation="block+receipt",
    )

    recognized, review = classify_hosts(hosts)

    if out_path:
        Path(out_path).write_text(to_yaml(generated), encoding="utf-8")

    return code, generated, {"recognized": recognized, "review": review, "session": stamp}
